/**
 * Generate valid-routes.mjs for Vercel Edge Middleware (soft 404 allowlist).
 */
import fs from 'fs'
import path from 'path'

const ROOT = path.resolve(import.meta.dirname, '..')

const STATIC_PATHS = [
  '/',
  '/about',
  '/products',
  '/factory',
  '/certifications',
  '/oem',
  '/markets',
  '/applications',
  '/faq',
  '/contact',
  '/blog',
  '/privacy',
  '/terms',
]

const PRODUCT_SLUGS = [
  'acetylene-cylinders',
  'propane-cylinders',
  'lpg-cylinders',
  'industrial-gas-cylinders',
  'generators',
  'welding-accessories',
  'refrigeration',
]

const routes = [...STATIC_PATHS]
for (const slug of PRODUCT_SLUGS) {
  routes.push(`/products/${slug}`)
}

const out = `/** Generated by scripts/generate-valid-routes.mjs — do not edit manually */\nexport const VALID_ROUTES = new Set(${JSON.stringify(routes, null, 2)})\n`

const target = path.join(ROOT, 'valid-routes.mjs')
fs.writeFileSync(target, out, 'utf8')
console.log(`Generated ${target} with ${routes.length} routes`)
